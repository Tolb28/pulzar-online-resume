#!/usr/bin/env python3
"""Build the template fonts (CV-2, CV-3).

For each font used by a template this writes:
  assets/fonts/<id>.ttf          – subset TrueType for the PDF (no layout tables, no hinting)
  public/static/fonts/<id>.woff2 – subset WOFF2 for the web page
and generates src/generated/charset.ts: the code points every template font can draw.
The editor uses it to flag characters that would not show in the PDF instead of
silently dropping them (CV-1 AC: "cuts nothing on its own").

All fonts are SIL OFL 1.1 without Reserved Font Names, so shipping subsets is allowed.
Their licences are copied next to the outputs.

Requires: pip install fonttools brotli   (run: npm run fonts)
"""
from __future__ import annotations

import os
import shutil
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
NM = ROOT / "node_modules" / "@expo-google-fonts"
PDF_OUT = ROOT / "assets" / "fonts"
WEB_OUT = ROOT / "public" / "static" / "fonts"
GEN_OUT = ROOT / "src" / "generated"

# id -> (package, weight folder, file)
FONTS = {
    "source-serif-4-700": ("source-serif-4", "700Bold", "SourceSerif4_700Bold.ttf"),
    "public-sans-400": ("public-sans", "400Regular", "PublicSans_400Regular.ttf"),
    "public-sans-600": ("public-sans", "600SemiBold", "PublicSans_600SemiBold.ttf"),
    "manrope-700": ("manrope", "700Bold", "Manrope_700Bold.ttf"),
    "inter-400": ("inter", "400Regular", "Inter_400Regular.ttf"),
    "inter-600": ("inter", "600SemiBold", "Inter_600SemiBold.ttf"),
    "space-grotesk-700": ("space-grotesk", "700Bold", "SpaceGrotesk_700Bold.ttf"),
    "dm-sans-400": ("dm-sans", "400Regular", "DMSans_400Regular.ttf"),
    "dm-sans-600": ("dm-sans", "600SemiBold", "DMSans_600SemiBold.ttf"),
}

# Latin for Czech, Slovak and the other European languages a CV here is likely to need,
# plus the punctuation and symbols people paste from Word.
RANGES = [
    (0x0020, 0x007E),  # Basic Latin
    (0x00A0, 0x00FF),  # Latin-1 Supplement
    (0x0100, 0x017F),  # Latin Extended-A (č ď ě ň ř š ť ů ž …)
    (0x0180, 0x024F),  # Latin Extended-B (ș ț …)
    (0x02C6, 0x02DD),  # spacing modifiers (ˇ ˘ ˙ ˚ ˛ ˜ ˝)
    (0x2000, 0x206F),  # General Punctuation („ “ ‚ ‘ – — … • ‰)
    (0x20A0, 0x20CF),  # Currency (€ …)
    (0x2100, 0x214F),  # Letterlike (™ № …)
    (0x2190, 0x21FF),  # Arrows
    (0x2200, 0x22FF),  # Mathematical operators (− ≤ ≥ …)
    (0x25A0, 0x25FF),  # Geometric shapes (■ ● ▪ …)
]
UNICODES = [cp for a, b in RANGES for cp in range(a, b + 1)]
WEB_FEATURES = ["kern", "liga", "calt", "ccmp", "locl", "mark", "mkmk"]


def make_subset(src: Path, dst: Path, *, flavor: str | None, features: list[str], hinting: bool) -> None:
    opts = subset.Options()
    opts.flavor = flavor
    opts.layout_features = features
    opts.hinting = hinting
    opts.name_IDs = ["*"]
    opts.name_languages = ["*"]
    opts.notdef_outline = True
    opts.recalc_bounds = True
    font = subset.load_font(str(src), opts)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    dst.parent.mkdir(parents=True, exist_ok=True)
    subset.save_font(font, str(dst), opts)


def ranges_of(cps: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in sorted(cps):
        if out and cp == out[-1][1] + 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def main() -> int:
    if not NM.exists():
        print("Run npm install first (fonts come from @expo-google-fonts/*).", file=sys.stderr)
        return 1
    common: set[int] | None = None
    families: set[str] = set()
    for fid, (pkg, folder, file) in FONTS.items():
        src = NM / pkg / folder / file
        make_subset(src, PDF_OUT / f"{fid}.ttf", flavor=None, features=[], hinting=False)
        make_subset(src, WEB_OUT / f"{fid}.woff2", flavor="woff2", features=WEB_FEATURES, hinting=True)
        cmap = set(TTFont(str(PDF_OUT / f"{fid}.ttf")).getBestCmap().keys())
        common = cmap if common is None else common & cmap
        families.add(pkg)
        print(f"{fid:20s} pdf {os.path.getsize(PDF_OUT / f'{fid}.ttf'):>7,d} B   web {os.path.getsize(WEB_OUT / f'{fid}.woff2'):>6,d} B")

    for pkg in sorted(families):
        lic = NM / pkg / "LICENSE_FONT"
        for out in (PDF_OUT / "licenses", WEB_OUT / "licenses"):
            out.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(lic, out / f"{pkg}-OFL.txt")

    assert common is not None
    rs = ranges_of(sorted(common))
    GEN_OUT.mkdir(parents=True, exist_ok=True)
    body = ",\n".join(f"  [0x{a:04x}, 0x{b:04x}]" for a, b in rs)
    (GEN_OUT / "charset.ts").write_text(
        "// Generated by scripts/build-fonts.py – do not edit.\n"
        "// Code points that every template font can draw (inclusive ranges).\n"
        f"export const SUPPORTED_RANGES: ReadonlyArray<readonly [number, number]> = [\n{body},\n];\n",
        encoding="utf-8",
    )
    print(f"charset: {len(common)} code points in {len(rs)} ranges")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
